require('dotenv').config()
if (process.env.NEON_DATABASE_URL) process.env.DATABASE_URL = process.env.NEON_DATABASE_URL

const axios = require('axios')
const JSZip = require('jszip')
const { PrismaClient } = require('@prisma/client')
const { cleanManifestZip } = require('./lib/clean-manifest')

async function fetchZip(base, appId, apiKey) {
  const url = `${base.replace(/\/$/, '')}/api/v2/generate/${appId}?format=zip`
  const res = await axios.get(url, {
    headers: { Authorization: `Bearer ${apiKey}`, Accept: 'application/zip, application/json' },
    responseType: 'arraybuffer',
    validateStatus: () => true,
    timeout: 120000,
  })
  const ct = String(res.headers['content-type'] || '')
  const buf = Buffer.from(res.data || [])
  return { url, status: res.status, ct, buf, isZip: buf.length > 2 && buf[0] === 0x50 && buf[1] === 0x4b }
}

async function inspectZip(label, buf) {
  console.log(`\n=== ${label} (${buf.length} bytes) ===`)
  const zip = await JSZip.loadAsync(buf)
  const names = Object.keys(zip.files).filter((n) => !zip.files[n].dir)
  console.log('files:', names.join(', ') || '(none)')
  for (const n of names) {
    if (!n.toLowerCase().endsWith('.lua')) continue
    const lua = await zip.file(n).async('string')
    console.log(`\n--- ${n} (first 600 chars) ---`)
    console.log(lua.slice(0, 600))
    const hasCredit = lua.includes('Generated by OpenSteam')
    console.log('has OpenSteam credit:', hasCredit)
  }
  const cleaned = await cleanManifestZip(buf)
  const changed = !cleaned.equals(buf)
  console.log('cleanManifestZip would change zip:', changed)
  if (changed) {
    const z2 = await JSZip.loadAsync(cleaned)
    for (const n of names) {
      if (!n.toLowerCase().endsWith('.lua')) continue
      const lua = await z2.file(n).async('string')
      console.log(`\n--- cleaned ${n} (first 400) ---`)
      console.log(lua.slice(0, 400))
    }
  }
}

async function main() {
  const appId = process.argv[2] || '730'
  const prisma = new PrismaClient()
  const row = await prisma.apiKey.findFirst({
    where: { enabled: true, user: { username: 'invisible7.' } },
    select: { key: true },
  })
  if (!row?.key) {
    const any = await prisma.apiKey.findFirst({ where: { enabled: true }, select: { key: true } })
    if (!any?.key) throw new Error('No API key in DB')
    row.key = any.key
  }

  const bases = [
    'https://manifest-web-ylio.onrender.com',
    'https://opensteam.lol',
    'http://opensteam.lol',
  ]

  for (const base of bases) {
    try {
      const r = await fetchZip(base, appId, row.key)
      console.log(`\n[${base}] status=${r.status} ct=${r.ct} zip=${r.isZip}`)
      if (!r.isZip) {
        console.log(r.buf.toString('utf8').slice(0, 400))
        continue
      }
      await inspectZip(base, r.buf)
    } catch (e) {
      console.log(`\n[${base}] ERROR`, e.message)
    }
  }

  await prisma.$disconnect()
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
