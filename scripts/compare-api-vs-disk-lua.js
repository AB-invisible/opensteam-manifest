require('dotenv').config()
if (process.env.NEON_DATABASE_URL) process.env.DATABASE_URL = process.env.NEON_DATABASE_URL

const fs = require('fs')
const axios = require('axios')
const JSZip = require('jszip')
const { PrismaClient } = require('@prisma/client')

async function main() {
  const appId = process.argv[2] || '3787240'
  const prisma = new PrismaClient()
  const row = await prisma.apiKey.findFirst({
    where: { enabled: true, user: { username: 'invisible7.' } },
    select: { key: true },
  })
  if (!row?.key) throw new Error('no key')

  const url = `https://manifest-web-ylio.onrender.com/api/v2/generate/${appId}?format=zip`
  const res = await axios.get(url, {
    headers: {
      Authorization: `Bearer ${row.key}`,
      Accept: 'application/zip, application/octet-stream, application/json',
    },
    responseType: 'arraybuffer',
    validateStatus: () => true,
    timeout: 120000,
  })

  console.log('status', res.status, 'ct', res.headers['content-type'], 'bytes', res.data?.byteLength)
  const buf = Buffer.from(res.data || [])
  const isZip = buf[0] === 0x50 && buf[1] === 0x4b
  console.log('isZip', isZip)
  if (!isZip) {
    console.log(buf.toString('utf8').slice(0, 500))
    return
  }

  const zip = await JSZip.loadAsync(buf)
  const luaName = Object.keys(zip.files).find((n) => n.toLowerCase().endsWith('.lua'))
  const apiLua = luaName ? await zip.file(luaName).async('string') : ''
  console.log('\n--- API lua head ---')
  console.log(apiLua.slice(0, 400))

  const diskPath = `C:\\Program Files (x86)\\Steam\\config\\stplug-in\\${appId}.lua`
  if (fs.existsSync(diskPath)) {
    const diskLua = fs.readFileSync(diskPath, 'utf8')
    console.log('\n--- DISK lua head ---')
    console.log(diskLua.slice(0, 400))
    console.log('\nmatch API:', diskLua === apiLua)
    console.log('disk has Hubcap:', /hubcap/i.test(diskLua))
    console.log('api has OpenSteam credit:', /Generated by OpenSteam/i.test(apiLua))
    const st = fs.statSync(diskPath)
    console.log('disk mtime', st.mtime.toISOString())
  } else {
    console.log('no disk lua at', diskPath)
  }

  await prisma.$disconnect()
}

main().catch(console.error)
