/**
 * JS twin of app/lib/clean-manifest.ts — used by scripts/bot-daemon.js since
 * the bot runs as plain Node (no TS pipeline). Keep the two files in sync.
 */
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '..', '.env') });
const JSZip = require('jszip');

function getSiteUrl() {
  const raw =
    process.env.NEXT_PUBLIC_APP_URL ||
    process.env.NEXTAUTH_URL ||
    'https://manifest-web-ylio.onrender.com';
  return String(raw).trim().replace(/\/$/, '');
}

function buildCredit() {
  return [
    '-- ────────────────────────────────────────────────────────────',
    '--  Generated by OpenSteam',
    `--  ${getSiteUrl()}`,
    '-- ────────────────────────────────────────────────────────────',
    '',
  ].join('\n');
}

const BANNED_FRAGMENTS = [
  'twentytwo cloud',
  'twentytwo server',
  'redistribution of twentytwo',
  'discord.com/invite/vwgwetftxw',
  'hubcap manifest',
  'hubcapmanifest.com',
  'depotbox',
  'depotbox.org',
  'total depots:',
  'total dlcs:',
  'shared depots:',
];

const RE_FUNC_CALL = /^(addappid|setManifestid)\s*\(/i;

function cleanLua(raw) {
  const cleanedLines = [];
  for (const line of raw.split(/\r?\n/)) {
    const stripped = line.trim();
    if (!stripped || stripped.startsWith('--')) continue;
    const low = stripped.toLowerCase();
    if (BANNED_FRAGMENTS.some(frag => low.includes(frag))) continue;
    if (!RE_FUNC_CALL.test(stripped)) continue;
    let parenDepth = 0;
    let cutAt = stripped.length;
    for (let i = 0; i < stripped.length; i++) {
      const ch = stripped[i];
      if (ch === '(') parenDepth++;
      else if (ch === ')') {
        parenDepth--;
        if (parenDepth === 0) {
          cutAt = i + 1;
          break;
        }
      }
    }
    let cleaned = stripped.slice(0, cutAt);
    // Normalize function name to canonical casing
    cleaned = cleaned.replace(/^addappid/i, 'addappid').replace(/^setmanifestid/i, 'setManifestid');
    cleanedLines.push(cleaned);
  }
  if (!cleanedLines.length || !cleanedLines.some(l => /^addappid\(/i.test(l))) {
    return null;
  }
  return buildCredit() + cleanedLines.join('\n') + '\n';
}

/** Returns a new Buffer with the lua inside the zip credited + cleaned, or the original on any failure. */
async function cleanManifestZip(input) {
  try {
    const zip = await JSZip.loadAsync(input);
    const luaNames = Object.keys(zip.files).filter(
      (n) => !zip.files[n].dir && n.toLowerCase().endsWith('.lua'),
    );
    if (luaNames.length === 0) return input;

    let changed = false;
    for (const luaName of luaNames) {
      const raw = await zip.file(luaName).async('string');
      const cleaned = cleanLua(raw);
      if (cleaned === null) continue;
      if (raw.replace(/\r/g, '') === cleaned) continue;
      zip.file(luaName, cleaned);
      changed = true;
    }

    if (!changed) return input;
    const out = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
    return Buffer.from(out);
  } catch (e) {
    console.warn('[clean-manifest] failed, serving original:', e && e.message);
    return input;
  }
}

module.exports = { cleanManifestZip };
