require('dotenv').config()
if (process.env.NEON_DATABASE_URL) process.env.DATABASE_URL = process.env.NEON_DATABASE_URL

const JSZip = require('jszip')
const { PrismaClient } = require('@prisma/client')
const { cleanManifestZip } = require('./lib/clean-manifest')

async function inspectBuffer(appId, buf) {
  const zip = await JSZip.loadAsync(buf)
  const luaFiles = Object.keys(zip.files).filter((n) => !zip.files[n].dir && n.toLowerCase().endsWith('.lua'))
  const cleaned = await cleanManifestZip(buf)
  const changed = !cleaned.equals(buf)
  const z2 = await JSZip.loadAsync(cleaned)
  let rawHasCredit = false
  let rawHasJunk = false
  let cleanedHasCredit = false
  for (const n of luaFiles) {
    const raw = await zip.file(n).async('string')
    if (raw.includes('Generated by OpenSteam')) rawHasCredit = true
    if (/depotbox|hubcap|twentytwo|total depots/i.test(raw)) rawHasJunk = true
    const out = await z2.file(n).async('string')
    if (out.includes('Generated by OpenSteam')) cleanedHasCredit = true
  }
  return { appId, luaFiles, changed, rawHasCredit, rawHasJunk, cleanedHasCredit }
}

async function main() {
  // Dynamic import compiled storage - use AWS SDK directly instead
  const { S3Client, GetObjectCommand } = require('@aws-sdk/client-s3')
  const prisma = new PrismaClient()
  const bucket = process.env.AWS_S3_BUCKET_NAME
  const s3 = bucket
    ? new S3Client({
        region: process.env.AWS_REGION || 'auto',
        endpoint: process.env.AWS_ENDPOINT || undefined,
        credentials: {
          accessKeyId: process.env.AWS_ACCESS_KEY_ID,
          secretAccessKey: process.env.AWS_SECRET_ACCESS_KEY,
        },
        forcePathStyle: !!process.env.AWS_ENDPOINT,
      })
    : null

  const manifests = await prisma.manifest.findMany({
    orderBy: { updatedAt: 'desc' },
    take: 20,
    select: { steamAppId: true, name: true, s3Key: true },
  })

  for (const m of manifests) {
    let buf = null
    if (s3 && bucket) {
      const key = m.s3Key || `manifests/${m.steamAppId}/${m.steamAppId}.zip`
      try {
        const out = await s3.send(new GetObjectCommand({ Bucket: bucket, Key: key }))
        const chunks = []
        for await (const c of out.Body) chunks.push(Buffer.from(c))
        buf = Buffer.concat(chunks)
      } catch (e) {
        console.log(JSON.stringify({ appId: m.steamAppId, name: m.name, error: e.message }))
        continue
      }
    }
    if (!buf?.length) continue
    const r = await inspectBuffer(m.steamAppId, buf)
    console.log(JSON.stringify({ name: m.name, ...r }))
  }

  await prisma.$disconnect()
}

main().catch(console.error)
